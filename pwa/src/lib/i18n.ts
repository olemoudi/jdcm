export const dictionaries = { es, en } as const
export type Lang = keyof typeof dictionaries

export function defaultLang(navLang: string | null = globalThis.navigator?.language ?? null): Lang {
  return navLang?.toLowerCase().startsWith('en') ? 'en' : 'es'
}

export function savedLang(): Lang {
  const v = readRaw('lang')
  return v === 'es' || v === 'en' ? v : defaultLang()
}

export function saveLang(lang: Lang | null): void {
  writeRaw('lang', lang)
}

export function translate(lang: Lang, key: Key, ...args: Array<string | number>): string {
  const s = dictionaries[lang][key] ?? dictionaries.es[key] ?? key
  return args.length ? s.replace(/\{(\d+)\}/g, (m, i) => (args[Number(i)] !== undefined ? String(args[Number(i)]) : m)) : s
}
